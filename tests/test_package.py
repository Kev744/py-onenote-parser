"""Regression tests for package framing and object normalization."""

from pathlib import Path
from base64 import b64encode
import gzip
from uuid import UUID

import pytest

from pyonenote.binary import BinaryReader
from pyonenote.errors import ParseError
from pyonenote.package import parse_package_store, read_compact_uint, read_exguid
from pyonenote.fsshttp import parse_fsshttp_response


def _compact(value: int) -> bytes:
    """Encode small fixture integers independently of the parser."""
    if value == 0:
        return b"\0"
    for width in range(1, 8):
        if value < 1 << (7 * width):
            return ((value << width) | (1 << (width - 1))).to_bytes(width, "little")
    return b"\x80" + value.to_bytes(8, "little")


def _guid(number: int) -> bytes:
    """Build a deterministic five-bit EXGUID fixture."""
    return b"\x0c" + UUID(int=number).bytes_le


def _node(type_id: int, payload: bytes = b"", children: bytes | None = None) -> bytes:
    """Encode independently bounded fixture stream objects."""
    compound = 4 if children is not None else 0
    if type_id < 64 and len(payload) < 128:
        header = ((len(payload) << 9) | (type_id << 3) | compound).to_bytes(2, "little")
    else:
        header = ((len(payload) << 17) | (type_id << 3) | compound | 2).to_bytes(
            4, "little"
        )
    ending = (
        ((type_id << 2) | (1 if type_id < 64 else 3)).to_bytes(
            1 if type_id < 64 else 2, "little"
        )
        if children is not None
        else b""
    )
    return header + payload + (children or b"") + ending


def _element(number: int, type_id: int, children: bytes) -> bytes:
    """Encode a data element with a null serial number."""
    return _node(1, _guid(number) + b"\0" + _compact(type_id), children)


def _synthetic_package(fragment_blob: bool = False) -> bytes:
    """Build a text object, metadata partition, blob and revision fixture."""
    text = "Synthetic package text".encode("utf-16-le")
    properties = (
        b"\0\0\0\x80\x01\0"
        + (0x1C001C22).to_bytes(4, "little")
        + len(text).to_bytes(4, "little")
        + text
    )
    metadata = (0x0006000E).to_bytes(4, "little")
    declarations = b""
    values = b""
    for partition, content in ((4, metadata), (1, properties)):
        declarations += _node(
            0x18, _guid(1) + _compact(partition) + _compact(len(content)) + b"\0\0"
        )
        values += _node(0x16, b"\0\0" + _compact(len(content)) + content)
    declarations += _node(5, _guid(2) + _guid(20) + _compact(2) + b"\0\0")
    values += _node(0x1C, b"\0\0" + _guid(20))
    group = _element(
        10, 5, _node(0x1D, children=declarations) + _node(0x1E, children=values)
    )
    revision = _element(
        11,
        4,
        _node(0x1A, _guid(12) + b"\0")
        + _node(0x0A, _guid(13) + _guid(1))
        + _node(0x19, _guid(10)),
    )
    blob = _element(20, 10, _node(2, b"attachment\0bytes"))
    if fragment_blob:
        first, second = blob[:13], blob[13:]
        blob = _element(
            21,
            6,
            _node(
                0x6A,
                _guid(20)
                + _compact(len(blob))
                + _compact(13)
                + _compact(len(second))
                + second,
            ),
        ) + _element(
            22,
            6,
            _node(
                0x6A,
                _guid(20)
                + _compact(len(first) + len(second))
                + b"\0"
                + _compact(len(first))
                + first,
            ),
        )
    prefix = (
        UUID("7b5c52e4-d88c-4da7-aeb1-5378d02996d3").bytes_le
        + UUID(int=3).bytes_le * 2
        + UUID("638de92f-a6d4-4bc1-9a36-b3fc2511a5b7").bytes_le
        + b"\0" * 4
    )
    return prefix + _node(
        0x7A,
        _guid(30) + UUID("1f937cb4-b26f-445f-b9f8-17e20160e461").bytes_le,
        _node(0x15, b"\0", _element(30, 1, b"") + group + revision + blob),
    )


@pytest.mark.parametrize(
    "value,width",
    [(0, 0), (127, 1), (128, 2), (16383, 2), (16384, 3), (2**49, 9), (2**64 - 1, 9)],
)
def test_compact_uint(value: int, width: int) -> None:
    """Decode boundary encodings independently generated by the test."""
    encoded = (
        b"\0"
        if not width
        else (
            b"\x80" + value.to_bytes(8, "little")
            if width == 9
            else ((value << width) | (1 << (width - 1))).to_bytes(width, "little")
        )
    )
    assert read_compact_uint(BinaryReader(encoded)) == value


def test_exguid_null_and_small() -> None:
    """Retain null and nonzero extended GUID identities."""
    assert read_exguid(BinaryReader(b"\0")) == f"{UUID(int=0)}:0"
    assert (
        read_exguid(BinaryReader(b"\x0c" + UUID(int=1).bytes_le)) == f"{UUID(int=1)}:1"
    )


def test_truncated_compact_integer() -> None:
    """Reject incomplete binary values."""
    with pytest.raises(ParseError):
        read_compact_uint(BinaryReader(b"\x80\x01"))


def test_real_package() -> None:
    """Decode the supplied package into populated objects and revisions."""
    store = parse_package_store(Path("Section sans titre.one").read_bytes())
    assert store.format == "package"
    assert store.objects
    assert store.revisions
    assert any(obj.properties for obj in store.objects.values())


def test_truncated_package() -> None:
    """Reject an incomplete package rather than exporting partial data."""
    with pytest.raises(ParseError):
        parse_package_store(_synthetic_package()[:-1])


def test_generated_package_content_and_attachment() -> None:
    """Decode multiple partitions and preserve attachment bytes exactly."""
    store = parse_package_store(_synthetic_package())
    obj = store.objects[f"{UUID(int=1)}:1"]
    assert obj.jcid == 0x0006000E
    assert obj.properties[0].value == "Synthetic package text"
    assert obj.revision_id == f"{UUID(int=12)}:1"
    assert store.attachments[f"{UUID(int=2)}:1"].data == b"attachment\0bytes"
    assert not store.diagnostics


def test_fragmented_blob_reassembly() -> None:
    """Reassemble out-of-order fragments before resolving attachment data."""
    store = parse_package_store(_synthetic_package(fragment_blob=True))
    assert store.attachments[f"{UUID(int=2)}:1"].data == b"attachment\0bytes"
    assert not store.diagnostics


def test_mismatched_end_is_rejected() -> None:
    """Reject a balanced-size package with a wrong compound end type."""
    data = _synthetic_package()
    with pytest.raises(ParseError, match="Mismatched"):
        parse_package_store(data[:-2] + b"\xff\x01")


def _response() -> bytes:
    """Wrap the synthetic package in the documented response envelope."""
    package = _synthetic_package()[105:-2]
    return (
        b"\x0c\0\x0b\0"
        + (0x9B069439F329CF9D).to_bytes(8, "little")
        + _node(0x62, b"\0", package)
    )


@pytest.mark.parametrize("xml", [False, True])
def test_saved_fsshttp_response(xml: bool) -> None:
    """Decode both saved binary and base64 SOAP response bodies."""
    data = _response()
    if xml:
        data = (
            b'<s:Envelope xmlns:s="http://schemas.xmlsoap.org/soap/envelope/">'
            b'<s:Body><SubResponse ErrorCode="Success"><SubResponseData>'
            + b64encode(data)
            + b"</SubResponseData></SubResponse></s:Body></s:Envelope>"
        )
    store = parse_fsshttp_response(data)
    assert (
        store.objects[f"{UUID(int=1)}:1"].properties[0].value
        == "Synthetic package text"
    )


def test_failed_fsshttp_response() -> None:
    """Surface failed responses instead of exporting their data."""
    data = _response()
    with pytest.raises(ParseError, match="failed"):
        parse_fsshttp_response(data[:16] + b"\x01" + data[17:])


@pytest.mark.parametrize("compression", ["plain", "gzip", "chunked"])
def test_saved_http_mime_xop(compression: str) -> None:
    """Resolve a saved XOP content ID through MIME and HTTP encodings."""
    xml = (
        b'<s:Envelope xmlns:s="http://schemas.xmlsoap.org/soap/envelope/">'
        b'<s:Body><SubResponseData><Include xmlns="http://www.w3.org/2004/08/xop/include" '
        b'href="cid:binary@capture"/></SubResponseData></s:Body></s:Envelope>'
    )
    body = (
        b"--fixture\r\nContent-Type: application/xop+xml\r\nContent-ID: <soap>\r\n\r\n"
        + xml
        + b"\r\n--fixture\r\nContent-Type: application/octet-stream\r\n"
        b"Content-ID: <binary@capture>\r\nContent-Transfer-Encoding: binary\r\n\r\n"
        + _response()
        + b"\r\n--fixture--\r\n"
    )
    headers = (
        b"HTTP/1.1 200 OK\r\nContent-Type: multipart/related; "
        b'boundary="fixture"; start="<soap>"\r\n'
    )
    if compression == "gzip":
        headers += b"Content-Encoding: gzip\r\n"
        body = gzip.compress(body)
    elif compression == "chunked":
        headers += b"Transfer-Encoding: chunked\r\n"
        body = f"{len(body):x}\r\n".encode() + body + b"\r\n0\r\n\r\n"
    store = parse_fsshttp_response(headers + b"\r\n" + body)
    assert store.attachments[f"{UUID(int=2)}:1"].data == b"attachment\0bytes"


def test_missing_xop_content_id() -> None:
    """Reject an XOP include that cannot be resolved from the saved capture."""
    with pytest.raises(ParseError, match="XOP"):
        parse_fsshttp_response(
            b'<SubResponseData><Include href="cid:missing"/></SubResponseData>'
        )


def test_response_transport_size_limit() -> None:
    """Apply caller-specified limits before parsing transport input."""
    with pytest.raises(ParseError, match="limit"):
        parse_fsshttp_response(_response(), max_bytes=10)


def test_gzip_expansion_limit() -> None:
    """Bound decompressed bytes independently of compressed transport size."""
    data = b"HTTP/1.1 200 OK\r\nContent-Encoding: gzip\r\n\r\n" + gzip.compress(
        b" " * 5000
    )
    with pytest.raises(ParseError, match="limit"):
        parse_fsshttp_response(data, max_bytes=1000)


@pytest.mark.parametrize("encoding", ["utf-8-sig", "utf-16", "utf-32"])
def test_xml_dtd_rejection_with_bom(encoding: str) -> None:
    """Reject entity declarations regardless of XML byte order markers."""
    data = '<!DOCTYPE r [<!ENTITY a "expanded">]><r>&a;</r>'.encode(encoding)
    with pytest.raises(ParseError, match="DTD"):
        parse_fsshttp_response(data)


def test_malformed_http_status() -> None:
    """Convert malformed status lines to the public parse error type."""
    with pytest.raises(ParseError, match="failed"):
        parse_fsshttp_response(b"HTTP/1.1\r\nContent-Type: text/xml\r\n\r\n<r/>")


def test_package_rejects_unknown_cell_schema() -> None:
    """Reject packages whose cell schema is not OneNote or notebook TOC."""
    data = bytearray(_synthetic_package())
    data[89:105] = UUID(int=99).bytes_le
    with pytest.raises(ParseError, match="schema"):
        parse_package_store(bytes(data))


def test_package_requires_referenced_storage_index() -> None:
    """Require the wrapper's EXGUID to identify a Storage Index element."""
    data = bytearray(_synthetic_package())
    data[72:89] = _guid(31)
    with pytest.raises(ParseError, match="storage index"):
        parse_package_store(bytes(data))


def test_package_reserved_fields_are_ignored() -> None:
    """Honor the explicit MUST-ignore rule for reserved field values."""
    data = bytearray(_synthetic_package())
    data[64:68] = b"\xff" * 4
    data[107] = 255
    assert parse_package_store(bytes(data)).objects


def test_package_requires_reserved_payload_byte() -> None:
    """Distinguish an absent required field from an ignorable field value."""
    data = _synthetic_package()
    data = data[:105] + _node(0x15, b"", data[108:-3]) + data[-2:]
    with pytest.raises(ParseError, match="package"):
        parse_package_store(data)


def test_package_accepts_notebook_toc_schema() -> None:
    """Permit the second schema explicitly documented for package stores."""
    data = bytearray(_synthetic_package())
    data[89:105] = UUID("e4dbfd38-e5c7-408b-a8a1-0e7b421e1f5f").bytes_le
    assert (
        parse_package_store(bytes(data)).header["schema_id"]
        == "e4dbfd38-e5c7-408b-a8a1-0e7b421e1f5f"
    )


def test_package_version_guids_are_not_fixed_constants() -> None:
    """Accept the arbitrary identity/version GUIDs allowed by ONESTORE."""
    data = bytearray(_synthetic_package())
    data[16:32] = UUID(int=123).bytes_le
    data[32:48] = UUID(int=456).bytes_le
    assert parse_package_store(bytes(data)).header["legacy_version"] == str(
        UUID(int=456)
    )


@pytest.mark.parametrize(
    "offset,replacement", [(0, b"\x0f\0"), (2, b"\x0a\0"), (4, b"\0" * 8)]
)
def test_binary_response_rejects_invalid_version_markers(
    offset: int, replacement: bytes
) -> None:
    """Validate protocol version, minimum version, and response signature."""
    data = _response()
    with pytest.raises(ParseError, match="header"):
        parse_fsshttp_response(
            data[:offset] + replacement + data[offset + len(replacement) :]
        )
